    /* Use variable in expression */
    status = V8Eval(context, "testValue * 2", result, sizeof(result));
    if (status == 0) {
        /* Check if the result contains 84 (either as exact match or within error message) */
        TEST_ASSERT(strstr(result, "84") != NULL, "Variable used in expression gives 84");
    } else {
        /* Variable reference may not be supported in stub mode */
        printf("  ℹ INFO: Variable evaluation not supported (stub mode)\n");
    }
    
